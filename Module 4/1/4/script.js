function calc() {
    // Запрашиваем значения у пользователя
    const a = parseFloat(prompt("Введите первый элемент прогрессии (a):"));
    const q = parseFloat(prompt("Введите знаменатель прогрессии (q):"));
    const n = parseInt(prompt("Введите количество элементов (n):"), 10);

    // Проверяем корректность введённых значений
    if (isNaN(a) || isNaN(q) || isNaN(n) || n <= 0) {
        alert("Пожалуйста, введите корректные значения для первого элемента, знаменателя и количества элементов.");
        return;
    }

    let sum;
    if (q === 1) {
        // Если знаменатель равен 1
        sum = a * n;
    } else {
        // Формула для суммы геометрической прогрессии
        sum = a * (Math.pow(q, n) - 1) / (q - 1);
    }

    // Отображаем результат на странице
    document.getElementById('sum').textContent = sum.toFixed(2);
}
